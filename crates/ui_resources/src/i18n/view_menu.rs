impl ViewMenuStrings {
    pub fn decade(&self, decade: i32) -> String {
        fill(&self.decade_t, &[&decade.to_string()])
    }

    pub fn unavailable_hidden(&self, count: usize) -> String {
        fill(&self.unavailable_hidden_t, &[&count.to_string()])
    }
}

pub fn view_menu_strings() -> &'static ViewMenuStrings {
    for_lang(active())
}

fn for_lang(lang: Lang) -> &'static ViewMenuStrings {
    match lang {
        Lang::En => &EN,
        Lang::Zh => &ZH,
        Lang::Pt => &PT,
        Lang::Ru => &RU,
        Lang::Ja => &JA,
        Lang::De => &DE,
        Lang::Fr => &FR,
        Lang::Ko => &KO,
        Lang::It => &IT,
        Lang::Tr => &TR,
        Lang::Pl => &PL,
        Lang::Nl => &NL,
        Lang::Uk => &UK,
        Lang::Vi => &VI,
        Lang::Id => &ID,
        Lang::Th => &TH,
        Lang::Cs => &CS,
        Lang::Sv => &SV,
        Lang::Hi => &HI,
        Lang::Es => &ES,
    }
}

