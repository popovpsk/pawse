impl EqualizerStrings {
    pub fn preamp(&self, db: &str) -> String {
        fill(&self.preamp_t, &[db])
    }

    pub fn index_failed(&self, error: &str) -> String {
        fill(&self.index_failed_t, &[error])
    }

    pub fn profile_failed(&self, name: &str, error: &str) -> String {
        fill(&self.profile_failed_t, &[name, error])
    }

    pub fn import_failed(&self, name: &str, error: &str) -> String {
        fill(&self.import_failed_t, &[name, error])
    }

    pub fn export_failed(&self, name: &str, error: &str) -> String {
        fill(&self.export_failed_t, &[name, error])
    }

    pub fn delete_profile(&self, name: &str) -> String {
        fill(&self.delete_profile_t, &[name])
    }

    pub fn delete_title(&self, name: &str) -> String {
        fill(&self.delete_title_t, &[name])
    }

    pub fn delete_failed(&self, name: &str, error: &str) -> String {
        fill(&self.delete_failed_t, &[name, error])
    }
}

pub fn equalizer_strings() -> &'static EqualizerStrings {
    for_lang(active())
}

fn for_lang(lang: Lang) -> &'static EqualizerStrings {
    match lang {
        Lang::En => &EN,
        Lang::Es => &ES,
        Lang::Zh => &ZH,
        Lang::Pt => &PT,
        Lang::Ru => &RU,
        Lang::Ja => &JA,
        Lang::De => &DE,
        Lang::Fr => &FR,
        Lang::Ko => &KO,
        Lang::It => &IT,
        Lang::Tr => &TR,
        Lang::Pl => &PL,
        Lang::Nl => &NL,
        Lang::Uk => &UK,
        Lang::Vi => &VI,
        Lang::Id => &ID,
        Lang::Th => &TH,
        Lang::Cs => &CS,
        Lang::Sv => &SV,
        Lang::Hi => &HI,
    }
}

